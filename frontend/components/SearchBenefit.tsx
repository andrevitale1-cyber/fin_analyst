"use client";

import { useEffect, useRef, useState } from "react";
import { motion, useInView, useReducedMotion } from "framer-motion";
import Image from "next/image";
import { Pause, Play, BarChart3, ChevronRight, Search, FileText } from "lucide-react";
import styles from "./SearchBenefit.module.css";

export default function SearchBenefit({ locale }: { locale: string }) {
  const card = useRef<HTMLElement>(null);
  const video = useRef<HTMLVideoElement>(null);
  const visible = useInView(card, { amount: .3 });
  const reduced = useReducedMotion();
  const [playing, setPlaying] = useState(false);
  const [userPaused, setUserPaused] = useState(false);
  const english = locale === "en";

  useEffect(() => {
    const element = video.current;
    if (!element) return;
    if (visible && !reduced && !userPaused) void element.play().catch(() => {});
    else element.pause();
  }, [visible, reduced, userPaused]);

  return <motion.article ref={card} className={styles.workflow} initial={reduced ? false : { opacity: 0, y: 32 }} whileInView={{ opacity: 1, y: 0 }} viewport={{ once: true, amount: .15 }} transition={{ duration: .6 }}>
    <div className={styles.intro}>
      <h3>{english ? "From company search to financial insight" : "Da busca da empresa à análise financeira"}</h3>
      <p>{english ? "Choose a company and period. FinAnalyzer finds the official document and turns it into an analysis with AI." : "Escolha a empresa e o período. O FinAnalyzer encontra o documento oficial e transforma os dados em uma análise com AI."}</p>
    </div>
    <div className={styles.flow}>
      <div className={styles.panel}>
        <div className={styles.panelHeader}><Search size={16} /><span>{english ? "Company search" : "Busca da empresa"}</span><span className={styles.step}>01</span></div>
        <div className={styles.media}>
          <video ref={video} src="/benefits/company-search-clean-7020ms.mp4#t=0.01" muted loop playsInline preload="metadata" aria-label={english ? "Company details and official report search demonstration" : "Demonstração do preenchimento da empresa e busca do documento oficial"} onPlay={() => setPlaying(true)} onPause={() => setPlaying(false)} />
          <button type="button" className={styles.control} aria-label={playing ? (english ? "Pause demonstration" : "Pausar demonstração") : (english ? "Play demonstration" : "Reproduzir demonstração")} onClick={() => {
            const element = video.current;
            if (!element) return;
            setUserPaused(playing);
            if (playing) element.pause(); else void element.play().catch(() => {});
          }}>{playing ? <Pause size={16} /> : <Play size={16} />}</button>
        </div>
        <p className={styles.caption}>{english ? "Enter the company, year and quarter." : "Informe a empresa, o ano e o trimestre."}</p>
      </div>
      <div className={styles.connection} aria-label="FinAnalyzer AI">
        <span className={styles.arrow}><ChevronRight size={14} /></span>
        <div className={styles.ai}><BarChart3 size={40} strokeWidth={2.2} aria-hidden="true" /><span>AI</span></div>
        <span className={styles.arrow}><ChevronRight size={14} /></span>
      </div>
      <div className={`${styles.panel} ${styles.destination}`}>
        <div className={styles.panelHeader}><FileText size={16} /><span>{english ? "Generated analysis" : "Análise gerada"}</span><span className={styles.step}>02</span></div>
        <div className={styles.report}><Image src="/benefits/generated-analysis.png" width={1430} height={660} alt={english ? "Meta analysis generated by FinAnalyzer, with financial scores and investment thesis" : "Análise da Meta gerada pelo FinAnalyzer, com notas financeiras e tese de investimento"} /></div>
        <p className={styles.caption}>{english ? "Explore the scores, investment thesis and source document." : "Explore as notas, a tese de investimento e o documento de origem."}</p>
      </div>
    </div>
  </motion.article>;
}
